import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
const records = [];
for (const file of await fs.readdir("docs/image-generation")) {
  if (!file.endsWith(".json")) continue;
  const record = JSON.parse(
    await fs.readFile(path.join("docs/image-generation", file), "utf8"),
  );
  const output = path.join("public/images", record.key + ".webp");
  await fs.mkdir(path.dirname(output), { recursive: true });
  const metadata = await sharp(record.path).metadata();
  const width = record.key === "hero" || record.key === "coast" ? 1920 : 1600;
  const main = await sharp(record.path)
    .resize({ width, withoutEnlargement: true })
    .webp({ quality: 83, effort: 5 })
    .toFile(output);
  const small = await sharp(record.path)
    .resize({ width: 720, withoutEnlargement: true })
    .webp({ quality: 78, effort: 5 })
    .toFile(output.replace(".webp", "-720.webp"));
  records.push({
    key: record.key,
    src: "/" + path.relative("public", output).replaceAll("\\", "/"),
    width: main.width,
    height: main.height,
    bytes: main.size,
    responsive: {
      src:
        "/" +
        path
          .relative("public", output)
          .replaceAll("\\", "/")
          .replace(".webp", "-720.webp"),
      width: small.width,
      height: small.height,
    },
    sourceWidth: metadata.width,
    sourceHeight: metadata.height,
    illustrative: true,
    generatedBy: "image_gen",
    promptRecord: "docs/image-generation/" + file,
  });
}
const groups = {};
for (const record of records)
  (groups[record.key.split("/")[0]] ??= []).push(record);
await fs.writeFile(
  "public/images/image-manifest.json",
  JSON.stringify(
    {
      description:
        "Photographs generated by AI for fictional properties. Not verified real listings.",
      groups,
    },
    null,
    2,
  ),
);
console.log(`Prepared ${records.length} images and 720px responsive versions.`);
